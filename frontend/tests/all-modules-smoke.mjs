import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const env=await readFile('../.env','utf8');
const teacherKey=env.split(/\r?\n/).find(line=>line.startsWith('TEACHER_API_KEY='))?.slice('TEACHER_API_KEY='.length);
const browser=await chromium.launch({headless:true});
const context=await browser.newContext({viewport:{width:1440,height:1000}});
await context.addInitScript(()=>{if(!localStorage.getItem('studymate-guest'))localStorage.setItem('studymate-guest','browser-test-'+crypto.randomUUID());});
const page=await context.newPage();const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:3000');
const panel=page.locator('#learning-plan');
await panel.getByRole('button',{name:'Build my plan'}).waitFor();
const exam=new Date(Date.now()+10*86400000).toISOString().slice(0,10);
await panel.getByLabel('Exam date').fill(exam);
await panel.getByLabel('Topics, one per line').fill('Waves\nLight');
await panel.getByRole('button',{name:'Build my plan'}).click();
await panel.getByText(/Study plan saved/).waitFor();
await panel.getByText('Record a practice score',{exact:true}).click();
await panel.getByLabel('Topic',{exact:true}).fill('Waves');
await panel.getByLabel('Marks earned').fill('2');
await panel.getByLabel('Marks possible').fill('10');
await panel.getByRole('button',{name:'Save score',exact:true}).click();
await panel.getByText(/Self-reported score saved/).waitFor();
await page.reload();await panel.getByText(`Exam: ${exam}`,{exact:true}).waitFor();
await page.screenshot({path:'../tmp/screenshots/all-modules-desktop.png',fullPage:true});
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:'../tmp/screenshots/all-modules-mobile.png',fullPage:true});
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
await panel.getByText('Saved dialogue and privacy',{exact:true}).click();
await panel.getByRole('button',{name:'Delete all my saved learning records'}).click();
await panel.getByText('Stored learning records deleted.',{exact:true}).waitFor();
await page.goto('http://127.0.0.1:3000/teacher');
await page.getByLabel('Teacher access key').fill(teacherKey);
await page.getByRole('button',{name:'Load analytics'}).click();
await page.getByRole('heading',{name:'Learning activity',exact:true}).waitFor();
await page.screenshot({path:'../tmp/screenshots/teacher-mobile.png',fullPage:true});
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
assert.deepEqual(errors,[]);
console.log('PASS: live planner, score feedback, saved-plan reload, deletion, teacher authentication/analytics and mobile layout.');
await browser.close();
